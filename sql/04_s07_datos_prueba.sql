FROM dbo.Pedido
GROUP BY YEAR(FechaPedido), Estado
ORDER BY Anio, Estado;

/* ===================  CONTROL DE INTEGRIDAD (todo debe salir 0)  =================== */
SELECT
    (SELECT COUNT(*) FROM dbo.DetallePedido d
       WHERE NOT EXISTS (SELECT 1 FROM dbo.Pedido   p WHERE p.PedidoID   = d.PedidoID))   AS Detalles_SinPedido,
    (SELECT COUNT(*) FROM dbo.DetallePedido d
       WHERE NOT EXISTS (SELECT 1 FROM dbo.Producto x WHERE x.ProductoID = d.ProductoID)) AS Detalles_SinProducto,
    (SELECT COUNT(*) FROM dbo.Pedido p
       WHERE NOT EXISTS (SELECT 1 FROM dbo.Cliente  c WHERE c.ClienteID  = p.ClienteID))  AS Pedidos_SinCliente,
    (SELECT COUNT(*) FROM dbo.Pedido p
       WHERE p.PedidoID > 40
         AND NOT EXISTS (SELECT 1 FROM dbo.DetallePedido d WHERE d.PedidoID = p.PedidoID)) AS Pedidos_Nuevos_SinDetalle;

/* ===================  ESCENARIOS DE PRUEBA IDENTIFICADOS  =================== */
-- Pedidos fijos: lineas e importe (Cantidad x PrecioUnitario)
SELECT p.PedidoID, p.ClienteID, p.FechaPedido, p.Estado,
       COUNT(d.DetalleID)                                       AS Lineas,
       ISNULL(SUM(d.Cantidad * d.PrecioUnitario), 0)           AS Importe
FROM dbo.Pedido p
LEFT JOIN dbo.DetallePedido d ON d.PedidoID = p.PedidoID
WHERE p.PedidoID IN (8, 11, 41, 42, 43, 44)
GROUP BY p.PedidoID, p.ClienteID, p.FechaPedido, p.Estado
ORDER BY p.PedidoID;

-- Clientes sin compra valida 2026: pedidos por estado (5 y 14 sin pedidos; 12 inactivo)
SELECT c.ClienteID, c.Nombre, c.Activo,
       SUM(CASE WHEN p.Estado = 'CONFIRMADO' AND YEAR(p.FechaPedido) = 2026 THEN 1 ELSE 0 END) AS Confirmados2026,
       SUM(CASE WHEN p.Estado <> 'CONFIRMADO' AND YEAR(p.FechaPedido) = 2026 THEN 1 ELSE 0 END) AS NoValidos2026
FROM dbo.Cliente c
LEFT JOIN dbo.Pedido p ON p.ClienteID = c.ClienteID
WHERE c.ClienteID IN (5, 6, 9, 12, 13, 14)
GROUP BY c.ClienteID, c.Nombre, c.Activo
ORDER BY c.ClienteID;
